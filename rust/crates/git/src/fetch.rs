//! Deterministic Fetch options and the exact command shared by preview and execution.

use lithe_protocol::{CoreError, ErrorCode};
use serde::{Deserialize, Serialize};

/// Per-operation submodule policy; inheritance preserves the user's Git configuration.
#[derive(Debug, Clone, Copy, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum GitFetchSubmodules {
    #[default]
    Inherit,
    No,
    OnDemand,
    Yes,
}

/// Tag transfer policy; inheritance leaves repository and remote configuration effective.
#[derive(Debug, Clone, Copy, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum GitFetchTags {
    #[default]
    Inherit,
    All,
    None,
    /// Also removes local tags absent from the fetched remote.
    Prune,
}

/// Structured Fetch choices. These never write repository or global configuration.
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase", default, deny_unknown_fields)]
pub struct GitFetchOptions {
    /// A configured remote name; null selects all remotes, preserving the legacy scope.
    pub remote: Option<String>,
    /// Remove stale remote-tracking references; false explicitly overrides fetch.prune.
    pub prune: bool,
    pub(crate) submodules: GitFetchSubmodules,
    pub(crate) tags: GitFetchTags,
}

impl Default for GitFetchOptions {
    fn default() -> Self {
        Self {
            remote: None,
            prune: true,
            submodules: GitFetchSubmodules::Inherit,
            tags: GitFetchTags::Inherit,
        }
    }
}

/// Preview input; an optional repository expands the plan into enabled remotes.
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct GitFetchPlanRequest {
    #[serde(default)]
    pub(crate) options: GitFetchOptions,
    /// Omit for a pure legacy argument preview.
    pub root: Option<String>,
}

/// Planned arguments are generated by the same function used immediately before Fetch.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GitFetchPlan {
    pub options: GitFetchOptions,
    /// Exact argument vector, excluding the executable; not evidence that Git has started.
    pub arguments: Vec<String>,
    /// Exact per-remote commands when a repository was supplied.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub commands: Option<Vec<Vec<String>>>,
}

/// Validates structured choices and builds temporary presentation configuration.
pub fn plan(request: GitFetchPlanRequest) -> Result<GitFetchPlan, CoreError> {
    let arguments = arguments(&request.options)?;
    let commands = request
        .root
        .as_ref()
        .map(|root| {
            let root = super::validate_root(root)?;
            super::fetch_execution::remote_names(&root, &request.options)?
                .into_iter()
                .map(|remote| {
                    let mut options = request.options.clone();
                    options.remote = Some(remote);
                    arguments_for_remote(&options)
                })
                .collect::<Result<Vec<_>, CoreError>>()
        })
        .transpose()?;
    Ok(GitFetchPlan {
        options: request.options,
        arguments,
        commands,
    })
}

fn arguments_for_remote(options: &GitFetchOptions) -> Result<Vec<String>, CoreError> {
    arguments(options)
}

pub(super) fn arguments(options: &GitFetchOptions) -> Result<Vec<String>, CoreError> {
    if let Some(remote) = &options.remote {
        // Reject option, URL, and absolute-path syntax while allowing remote
        // names with punctuation. Execution verifies the name is configured.
        if remote.is_empty()
            || remote.starts_with(['-', '/', '.'])
            || remote.ends_with(['/', '.'])
            || remote.contains("..")
            || remote.contains("//")
            || remote.contains("@{")
            || remote.split('/').any(|part| part.ends_with(".lock"))
            || remote
                .chars()
                .any(|c| c.is_control() || c.is_whitespace() || ":\\~^?*[".contains(c))
        {
            return Err(CoreError::new(
                ErrorCode::InvalidRequest,
                "Fetch requires a remote name",
            ));
        }
    }
    // These flags affect this invocation only. Authentication, proxy, signing,
    // and submodule configuration remain inherited unless explicitly selected.
    let mut arguments = vec![
        "--no-pager".into(),
        "-c".into(),
        "color.ui=false".into(),
        "-c".into(),
        "core.quotepath=false".into(),
        "fetch".into(),
        "--progress".into(),
    ];
    if options.remote.is_none() {
        arguments.push("--all".into());
    }
    arguments.push(
        if options.prune {
            "--prune"
        } else {
            "--no-prune"
        }
        .into(),
    );
    match options.tags {
        GitFetchTags::Inherit => {}
        GitFetchTags::All => arguments.push("--tags".into()),
        GitFetchTags::None => arguments.push("--no-tags".into()),
        GitFetchTags::Prune => {
            if !options.prune {
                return Err(CoreError::new(
                    ErrorCode::InvalidRequest,
                    "Tag pruning requires pruning stale references",
                ));
            }
            arguments.push("--prune-tags".into());
        }
    }
    match options.submodules {
        GitFetchSubmodules::Inherit => {}
        GitFetchSubmodules::No => arguments.push("--recurse-submodules=no".into()),
        GitFetchSubmodules::OnDemand => arguments.push("--recurse-submodules=on-demand".into()),
        GitFetchSubmodules::Yes => arguments.push("--recurse-submodules=yes".into()),
    }
    if let Some(remote) = &options.remote {
        arguments.extend(["--".into(), remote.clone()]);
    }
    Ok(arguments)
}

#[cfg(test)]
mod tests {
    use serde_json::Value;

    /// The arguments the executor passes to `git fetch` are the ones `git.fetchPlan` reports.
    #[test]
    fn fetch_arguments_match_the_shared_fixture() {
        let fixture: Value =
            serde_json::from_str(include_str!("../../../fixtures/git/fetch-plan-v1.json")).unwrap();
        for case in fixture["cases"].as_array().unwrap() {
            let options = serde_json::from_value(case["expectedOptions"].clone()).unwrap();
            assert_eq!(
                serde_json::to_value(super::arguments(&options).unwrap()).unwrap(),
                case["arguments"]
            );
        }
    }
}
